/*!
 * \file p_relu_grad_update_tiling_key.h
 * \brief Tiling template keys for supported dtypes.
 */

#ifndef PRELUGRADUPDATE_TILING_KEY_H
#define PRELUGRADUPDATE_TILING_KEY_H

#include "ascendc/host_api/tiling/template_argument.h"

#define PRELUGRADUPDATE_TPL_FLOAT 0
#define PRELUGRADUPDATE_TPL_FLOAT16 1
#define PRELUGRADUPDATE_TPL_BF16 2

// P026: 平台第4点 ACL 507035（向量核异常）——在仅 fp32 注册时，后续点多为 fp16/bf16。
// 重新打开三 dtype；kernel 侧禁止任何 Cast（half/bf16 走标量/位转换）。
#ifndef PRELU_ENABLE_FP16
#define PRELU_ENABLE_FP16 1
#endif
#ifndef PRELU_ENABLE_BF16
#define PRELU_ENABLE_BF16 1
#endif

#if PRELU_ENABLE_BF16 && PRELU_ENABLE_FP16
ASCENDC_TPL_ARGS_DECL(
    PReluGradUpdate,
    ASCENDC_TPL_UINT_DECL(schMode, 2, ASCENDC_TPL_UI_LIST,
        PRELUGRADUPDATE_TPL_FLOAT, PRELUGRADUPDATE_TPL_FLOAT16, PRELUGRADUPDATE_TPL_BF16));
ASCENDC_TPL_SEL(ASCENDC_TPL_ARGS_SEL(
    ASCENDC_TPL_UINT_SEL(schMode, ASCENDC_TPL_UI_LIST,
        PRELUGRADUPDATE_TPL_FLOAT, PRELUGRADUPDATE_TPL_FLOAT16, PRELUGRADUPDATE_TPL_BF16)));
#elif PRELU_ENABLE_FP16
ASCENDC_TPL_ARGS_DECL(
    PReluGradUpdate,
    ASCENDC_TPL_UINT_DECL(schMode, 2, ASCENDC_TPL_UI_LIST,
        PRELUGRADUPDATE_TPL_FLOAT, PRELUGRADUPDATE_TPL_FLOAT16));
ASCENDC_TPL_SEL(ASCENDC_TPL_ARGS_SEL(
    ASCENDC_TPL_UINT_SEL(schMode, ASCENDC_TPL_UI_LIST,
        PRELUGRADUPDATE_TPL_FLOAT, PRELUGRADUPDATE_TPL_FLOAT16)));
#else
ASCENDC_TPL_ARGS_DECL(
    PReluGradUpdate,
    ASCENDC_TPL_UINT_DECL(schMode, 2, ASCENDC_TPL_UI_LIST, PRELUGRADUPDATE_TPL_FLOAT));
ASCENDC_TPL_SEL(ASCENDC_TPL_ARGS_SEL(
    ASCENDC_TPL_UINT_SEL(schMode, ASCENDC_TPL_UI_LIST, PRELUGRADUPDATE_TPL_FLOAT)));
#endif

#endif
